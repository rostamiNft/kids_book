#!/usr/bin/env python3
"""
build_pdf.py -- assemble finished AI page images into a single PDF.

This script is the ONLY code step in the book pipeline. It does not draw,
render, or typeset anything: every page image already contains its artwork
and its text, generated by the image model. Pillow only stitches the finished
images into one PDF, one image per page.

Usage
-----
    python tools/build_pdf.py 10_The_Little_Library_of_Lost_Things
    python tools/build_pdf.py 10_... --expect 20 --width 768 --height 1376
    python tools/build_pdf.py 10_... --out /tmp/preview.pdf --no-verify

Exit code 0 on success, 1 on any validation failure.
"""

from __future__ import annotations

import argparse
import glob
import os
import sys


def natural_page_key(path: str) -> int:
    """page_07.png -> 7"""
    base = os.path.basename(path)
    digits = "".join(ch for ch in base if ch.isdigit())
    return int(digits) if digits else 0


def collect_pages(book_dir: str, pattern: str, expect: int) -> list[str]:
    files = sorted(glob.glob(os.path.join(book_dir, "illustrations", pattern)),
                   key=natural_page_key)
    if not files:
        sys.exit(f"ERROR: no page images found in {book_dir}/illustrations/{pattern}")

    numbers = [natural_page_key(f) for f in files]
    missing = [n for n in range(1, (expect or max(numbers)) + 1) if n not in numbers]
    if missing:
        sys.exit(f"ERROR: missing page numbers: {missing}")

    if expect and len(files) != expect:
        sys.exit(f"ERROR: expected {expect} pages, found {len(files)}")
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description="Assemble AI-generated page images into a PDF.")
    ap.add_argument("book_dir", help="book folder, e.g. 10_The_Little_Library_of_Lost_Things")
    ap.add_argument("--pattern", default="page_*.png", help="glob under illustrations/ (default page_*.png)")
    ap.add_argument("--expect", type=int, default=20, help="required page count (default 20, 0 = any)")
    ap.add_argument("--width", type=int, default=768, help="required width in px (default 768)")
    ap.add_argument("--height", type=int, default=1376, help="required height in px (default 1376)")
    ap.add_argument("--out", default=None, help="output PDF path (default <book>/pdf/<book title>.pdf)")
    ap.add_argument("--dpi", type=float, default=72.0, help="resolution metadata written into the PDF")
    ap.add_argument("--no-verify", action="store_true", help="skip the pypdf read-back check")
    args = ap.parse_args()

    from PIL import Image

    book_dir = args.book_dir.rstrip("/")
    if not os.path.isdir(book_dir):
        return fail(f"{book_dir} is not a directory")

    files = collect_pages(book_dir, args.pattern, args.expect)
    target = (args.width, args.height)

    images = []
    for path in files:
        im = Image.open(path)
        if im.mode != "RGB":
            im = im.convert("RGB")
        if im.size != target:
            return fail(f"{path}: size {im.size} != required {target}")
        images.append(im)
    print(f"validated {len(images)} pages at {target[0]}x{target[1]} RGB")

    if args.out:
        out = args.out
    else:
        name = os.path.basename(os.path.abspath(book_dir)).split("_", 1)[-1]
        name = name.replace("_", " ")
        out = os.path.join(book_dir, "pdf", f"{name}.pdf")
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)

    images[0].save(out, save_all=True, append_images=images[1:], resolution=args.dpi)
    size_kb = round(os.path.getsize(out) / 1024)
    print(f"wrote {out} ({len(images)} pages, {size_kb} KB)")

    if not args.no_verify:
        from pypdf import PdfReader
        reader = PdfReader(out)
        boxes = {(round(float(p.mediabox.width)), round(float(p.mediabox.height)))
                 for p in reader.pages}
        print(f"pypdf read-back: {len(reader.pages)} pages, page sizes {boxes}")
        if len(reader.pages) != len(images):
            return fail("PDF page count does not match image count")
        if len(boxes) != 1:
            return fail(f"PDF pages have mixed sizes: {boxes}")
        w, h = boxes.pop()
        if abs(w - target[0]) > 1 or abs(h - target[1]) > 1:
            return fail(f"PDF page size {(w, h)} != {target}")
        print("PDF OK")
    return 0


def fail(msg: str) -> int:
    print(f"ERROR: {msg}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
